"""Post-migration guidance for RLS and credential templates.

Sprint 119 — Automate manual post-migration steps.

Functions:
    generate_rls_powershell: Generate a blocking RLS review reminder.
    generate_credential_template: Generate a user-friendly JSON template
        with placeholder credentials for each datasource connection.
"""

import json
import logging
import os
import re

logger = logging.getLogger(__name__)


# ── RLS PowerShell script generation ──────────────────────────────────────────

def generate_rls_powershell(roles, output_path, dataset_name="MyDataset"):
    """Write a blocking reminder to review RLS role membership manually.

    Args:
        roles: list of role dicts from TMDL/BIM, each with 'name' and
            optionally 'members' (list of BO usernames) and
            'tablePermissions'.
        output_path: File path to write the .ps1 script.
        dataset_name: Retained for compatibility; not included in the script.

    Returns:
        str: Path to the generated .ps1 file, or None on error.
    """
    if not roles:
        return None

    lines = [
        "# Generated by BO-to-Power-BI Migration Tool",
        "# No roles, users, permissions or connections are configured by this file.",
        "# Review the source restrictions and identities with the security owner.",
        "# Assign reviewed role membership using supported Power BI administration tools.",
        "# Test allowed and denied access in the authorized target environment.",
        'throw "Automatic RLS role assignment is unsupported; configure and validate it manually."',
    ]

    try:
        os.makedirs(os.path.dirname(output_path) or '.', exist_ok=True)
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write('\n'.join(lines) + '\n')
        logger.info("RLS PowerShell script written: %s", output_path)
        return output_path
    except OSError as exc:
        logger.warning("Failed to write RLS script: %s", exc)
        return None


# ── Credential template generation ────────────────────────────────────────────

def generate_credential_template(datasources, output_path):
    """Generate a JSON credential template with placeholders for each datasource.

    Creates a user-friendly file with connection details extracted from the
    BO report, with placeholder values for sensitive fields (password,
    OAuth tokens, service account keys).

    Args:
        datasources: list of datasource dicts from extraction (each has
            'connection' with server, port, database, authentication, etc.).
        output_path: File path to write the template JSON.

    Returns:
        str: Path to the generated file, or None on error.
    """
    if not datasources:
        return None

    template = {
        "_comment": "Credential template for Power BI datasource connections. "
                    "Fill in the placeholder values and use with gateway configuration.",
        "connections": [],
    }

    seen = set()
    for ds in datasources:
        conn = ds.get('connection', {})
        if not conn:
            # Try connection_map for multi-connection datasources
            conn_map = ds.get('connection_map', {})
            if conn_map:
                for cname, cinfo in conn_map.items():
                    _add_credential_entry(template['connections'], cinfo, cname, seen)
                continue
            continue
        _add_credential_entry(template['connections'], conn, ds.get('name', ''), seen)

    if not template['connections']:
        return None

    try:
        os.makedirs(os.path.dirname(output_path) or '.', exist_ok=True)
        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(template, f, indent=2, ensure_ascii=False)
        logger.info("Credential template written: %s", output_path)
        return output_path
    except OSError as exc:
        logger.warning("Failed to write credential template: %s", exc)
        return None


def _add_credential_entry(connections_list, conn, name, seen):
    """Build a single credential entry from a connection dict."""
    server = conn.get('server', conn.get('host', ''))
    database = conn.get('dbname', conn.get('database', ''))
    conn_type = conn.get('class', conn.get('type', 'unknown'))
    port = conn.get('port', '')

    # Deduplicate by server+database
    key = f"{conn_type}:{server}:{database}"
    if key in seen:
        return
    seen.add(key)

    entry = {
        "name": name,
        "type": conn_type,
        "server": server or "YOUR_SERVER",
        "port": port or "",
        "database": database or "YOUR_DATABASE",
        "authentication": conn.get('authentication', 'sql'),
        "username": "YOUR_USERNAME",
        "password": "YOUR_PASSWORD",
        "_note": "Replace placeholder values with actual credentials. "
                 "For OAuth, use the oauth_token field instead of username/password.",
    }

    # Add OAuth fields for cloud connectors
    if conn_type in ('bigquery', 'snowflake', 'databricks', 'google_sheets',
                      'salesforce', 'redshift', 'azure_sql_dw'):
        entry['oauth_token'] = "YOUR_OAUTH_TOKEN"
        entry['oauth_refresh_token'] = "YOUR_REFRESH_TOKEN"

    # Add service account for GCP
    if conn_type in ('bigquery', 'google_sheets'):
        entry['service_account_key_path'] = "path/to/service-account.json"

    connections_list.append(entry)


# ── BO Security Profile → RLS Role mapping ────────────────────────────────────

def map_bo_security_profiles(profiles, tables):
    """Map declared BO restrictions to candidate Power BI RLS metadata.

    Candidate filters require independent review of source semantics, target
    data types and access behavior; this does not establish equivalence.

    Args:
        profiles: list of BO security profile dicts, each with:
            - name: profile name (e.g., "Sales EMEA")
            - restrictions: list of dicts with 'object', 'operator', 'values'
            - members: list of BO user/group names
        tables: list of table dicts from extraction (for column resolution).

    Returns:
        list of candidate role dicts, each with
        'name', 'members', and 'tablePermissions'.

    Raises:
        ValueError: If a restriction cannot be resolved or represented.
    """
    if not profiles:
        return []

    col_table = {}
    for tbl in (tables or []):
        tbl_name = tbl.get('name', '')
        for col in tbl.get('columns', []):
            col_name = col.get('name', '') if isinstance(col, dict) else col
            if not isinstance(tbl_name, str) or not tbl_name.strip():
                raise ValueError("A table with columns must have a nonempty name")
            if not isinstance(col_name, str) or not col_name.strip():
                raise ValueError("A column must have a nonempty name")
            col_table.setdefault(col_name.casefold(), []).append((tbl_name, col_name))

    roles = []
    for profile in profiles:
        if not isinstance(profile, dict):
            raise ValueError("A security profile must be an object")
        profile_name = profile.get('name', 'UnknownProfile')
        restrictions = profile.get('restrictions', [])
        members = profile.get('members', [])

        if not isinstance(restrictions, list) or not restrictions:
            raise ValueError("Each security profile must declare restrictions")

        table_permissions = []
        for restriction in restrictions:
            if not isinstance(restriction, dict):
                raise ValueError("A restriction must be an object")
            obj_name = restriction.get('object', '')
            operator = restriction.get('operator')
            values = restriction.get('values', [])

            if not isinstance(obj_name, str) or not obj_name.strip():
                raise ValueError("A restriction must identify a column")
            matches = col_table.get(obj_name.casefold(), [])
            if len(matches) != 1:
                raise ValueError("Restriction column is missing or ambiguous")
            resolved_table, resolved_column = matches[0]
            dax_filter = _build_rls_filter(resolved_table, resolved_column, operator, values)
            table_permissions.append({
                'table': resolved_table,
                'filterExpression': dax_filter,
            })

        roles.append({
            'name': _sanitize_role_name(profile_name),
            'members': members,
            'tablePermissions': table_permissions,
        })

    return roles


def _build_rls_filter(table_name, column_name, operator, values):
    """Build a DAX filter expression for an RLS table permission.

    Args:
        table_name: Resolved table name.
        column_name: Column to filter.
        operator: BO operator ('=', 'InList', 'Between', '<>', etc.).
        values: List of filter values.

    Returns:
        str: DAX filter expression (e.g., ``'Sales'[Region] = "EMEA"``).
    """
    if not isinstance(operator, str) or not operator.strip():
        raise ValueError("A restriction must declare an operator")
    if not isinstance(values, list) or not values or any(
        not isinstance(value, str) for value in values
    ):
        raise ValueError("Restriction values must be a nonempty list of strings")

    op_lower = operator.lower()
    list_operators = ('=', 'inlist', 'in', '<>', 'notequal', 'not equal')
    scalar_operators = (
        'equal', 'equals', '>', 'greater', '<', 'less', '>=',
        'greaterorequal', '<=', 'lessorequal', 'like', 'matches pattern',
    )
    if op_lower in scalar_operators and len(values) != 1:
        raise ValueError("Restriction operator requires exactly one value")
    if op_lower == 'between' and len(values) != 2:
        raise ValueError("Between requires exactly two values")
    if op_lower not in (*list_operators, *scalar_operators, 'between'):
        raise ValueError("Unsupported restriction operator")

    escaped_table = table_name.replace("'", "''")
    escaped_column = column_name.replace(']', ']]')
    col_ref = f"'{escaped_table}'[{escaped_column}]"
    values = [value.replace('"', '""') for value in values]

    if op_lower in ('=', 'equal', 'equals') and len(values) == 1:
        return f'{col_ref} = "{values[0]}"'
    elif op_lower in ('inlist', 'in') or (op_lower == '=' and len(values) > 1):
        items = " || ".join(f'{col_ref} = "{v}"' for v in values)
        return items
    elif op_lower in ('<>', 'notequal', 'not equal'):
        items = " && ".join(f'{col_ref} <> "{v}"' for v in values)
        return items
    elif op_lower == 'between':
        return f'{col_ref} >= "{values[0]}" && {col_ref} <= "{values[1]}"'
    elif op_lower in ('>', 'greater'):
        return f'{col_ref} > "{values[0]}"'
    elif op_lower in ('<', 'less'):
        return f'{col_ref} < "{values[0]}"'
    elif op_lower in ('>=', 'greaterorequal'):
        return f'{col_ref} >= "{values[0]}"'
    elif op_lower in ('<=', 'lessorequal'):
        return f'{col_ref} <= "{values[0]}"'
    elif op_lower in ('like', 'matches pattern'):
        # BO LIKE with wildcards → DAX PATHCONTAINS or CONTAINSSTRING
        pattern_val = values[0].replace('%', '*')
        return f'CONTAINSSTRING({col_ref}, "{pattern_val}")'


def _sanitize_role_name(name):
    """Sanitize a BO profile name for use as a PBI RLS role name."""
    # Remove characters not allowed in TMDL role names
    sanitized = re.sub(r'[^\w\s\-]', '', name).strip()
    return sanitized or "DefaultRole"
